/**
 * Generates SQL you can paste into the Supabase SQL Editor (no terminal needed):
 *
 *   supabase/setup.sql              full schema for a NEW project (all migrations)
 *   supabase/upgrades/<tag>.sql     one file per migration, for a project that is
 *                                   already set up — run only the ones you haven't
 *
 * Each file enables RLS on the tables it creates (the app uses the database role,
 * which bypasses RLS; Supabase's public Data API stays closed) and records the
 * migration in drizzle.__drizzle_migrations so `npm run db:migrate` stays in sync.
 *
 *   node scripts/gen-supabase-sql.mjs
 */
import { createHash } from "crypto";
import { mkdirSync, readFileSync, writeFileSync } from "fs";

const dir = "src/server/db/migrations";
const journal = JSON.parse(readFileSync(`${dir}/meta/_journal.json`, "utf8"));

const bookkeeping = `CREATE SCHEMA IF NOT EXISTS "drizzle";
CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (
  id SERIAL PRIMARY KEY,
  hash text NOT NULL,
  created_at bigint
);`;

function migrationSql(e) {
  const query = readFileSync(`${dir}/${e.tag}.sql`, "utf8");
  const hash = createHash("sha256").update(query).digest("hex");
  const tables = [...query.matchAll(/CREATE TABLE "(\w+)"/g)].map((m) => m[1]);
  const body = query
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => (s.endsWith(";") ? s : s + ";"))
    .join("\n\n");
  const rls = tables.map((t) => `ALTER TABLE "${t}" ENABLE ROW LEVEL SECURITY;`).join("\n");
  const record = `INSERT INTO "drizzle"."__drizzle_migrations" ("hash", "created_at") VALUES ('${hash}', ${e.when}); -- ${e.tag}`;
  return { body, rls, record, tables };
}

const header = (title) => `-- =====================================================================
-- REIMI platform — ${title}
-- Generated by scripts/gen-supabase-sql.mjs. Paste into Supabase → SQL Editor → Run.
-- =====================================================================
BEGIN;
`;

const all = journal.entries.map((e) => ({ e, ...migrationSql(e) }));

let setup = header("full setup for a NEW project (run once)");
for (const m of all) setup += `\n-- ---------- migration ${m.e.tag} ----------\n${m.body}\n`;
setup += `\n-- ---------- Row Level Security (closed to the public Data API) ----------\n${all.map((m) => m.rls).filter(Boolean).join("\n")}\n`;
setup += `\n-- ---------- migration bookkeeping ----------\n${bookkeeping}\n${all.map((m) => m.record).join("\n")}\n\nCOMMIT;\n`;
writeFileSync("supabase/setup.sql", setup);

mkdirSync("supabase/upgrades", { recursive: true });
for (const m of all.slice(2)) {
  // 0000/0001 are the initial setup; upgrades start at 0002
  let up = header(`upgrade ${m.e.tag} (run once, only if your project was set up before this file existed)`);
  up += `\n-- Skips itself if this migration was already applied.\nDO $$ BEGIN\n  IF EXISTS (SELECT 1 FROM "drizzle"."__drizzle_migrations" WHERE created_at = ${m.e.when}) THEN\n    RAISE EXCEPTION 'already applied: ${m.e.tag}';\n  END IF;\nEND $$;\n`;
  up += `\n${m.body}\n\n${m.rls}\n\n${m.record}\n\nCOMMIT;\n`;
  writeFileSync(`supabase/upgrades/${m.e.tag}.sql`, up);
}
console.log(`setup.sql: ${all.reduce((s, m) => s + m.tables.length, 0)} tables, ${all.length} migrations; upgrades: ${Math.max(0, all.length - 2)}`);
